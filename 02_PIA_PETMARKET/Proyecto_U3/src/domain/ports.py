from typing import Protocol
class PedidoRepository(Protocol):
    def obtener(self, pedido_id:str): ...
    def guardar(self, pedido): ...
class InventarioRepository(Protocol):
    def obtener(self, almacen_id:str, sku:str): ...
    def guardar(self, existencia): ...
class PreparacionRepository(Protocol):
    def guardar(self, orden): ...
    def listar_por_pedido(self, pedido_id:str): ...
class PasarelaPago(Protocol):
    def cobrar(self, pedido_id:str, monto:str)->bool: ...
class UnitOfWork(Protocol):
    def iniciar(self): ...
    def confirmar(self): ...
    def revertir(self): ...
