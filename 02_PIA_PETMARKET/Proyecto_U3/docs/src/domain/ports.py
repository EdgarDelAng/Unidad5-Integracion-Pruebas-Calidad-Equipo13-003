"""Puertos del dominio: la lógica del dominio no importa infraestructura."""
from typing import Protocol
from .model import Pedido,ExistenciaInventario,OrdenPreparacion
class PedidoRepository(Protocol):
    def obtener(self,pedido_id:str)->Pedido|None: ...
    def guardar(self,pedido:Pedido)->None: ...
class InventarioRepository(Protocol):
    def obtener(self,almacen_id:str,sku:str)->ExistenciaInventario|None: ...
    def guardar(self,existencia:ExistenciaInventario)->None: ...
class PreparacionRepository(Protocol):
    def guardar(self,orden:OrdenPreparacion)->None: ...
    def listar_por_pedido(self,pedido_id:str)->list[OrdenPreparacion]: ...
    def obtener(self,orden_id:str)->OrdenPreparacion|None: ...
class PasarelaPago(Protocol):
    def cobrar(self,pedido_id:str,monto:str)->bool: ...
class UnitOfWork(Protocol):
    def iniciar(self)->None: ...
    def confirmar(self)->None: ...
    def revertir(self)->None: ...
